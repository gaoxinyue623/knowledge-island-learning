export const revisedChinesePracticeRows = revisedChineseLowerRows.map((row) => {
  const definition = byKey[row.key]
  if (!definition) throw new Error(`REVISED_CHINESE_PRACTICE_MISSING:${row.key}`)
  return { ...row, practice: definition }
})

export const revisedChineseReadingSeeds: ReadingQuestionSeed[] = revisedChinesePracticeRows.map(
  (row) => ({
    textbookId: G2_REVISED_CHINESE_TEXTBOOK_ID,
    title: row.title.replace(/^\d+\s*/u, ''),
    evidence: row.practice.evidence,
    prompt: row.practice.prompt,
    answer: row.practice.answer,
    distractors: [...row.practice.distractors],
    wordPairs: row.practice.words.map((word): [string, string] => [word[0]!, word]),
    explanation: `文中依据：“${row.practice.evidence}”。${row.practice.answer}。`,
  }),
)
